# Собирает 30 шрифтов в fonts/ (TrueType через fontTools) и листы-образцы в tools/fontgen/proof/.
# Запуск: python tools/fontgen/build.py [номер|имя …]   (без аргументов — все)
import math
import os
import sys

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import skeleton  # noqa: E402
from styles import STYLES  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "fonts")
PROOF = os.path.join(HERE, "proof")


def side(st, cls):
    return st.sb * {"s": 1.0, "r": 0.78, "d": 0.3, "p": 0.55}[cls]


def draw_glyph(st, ch):
    fn, Wn, hk, sp = skeleton.REG[ch]
    H = st.CAP if hk == "C" else st.XH
    if Wn == 0:
        W = st.nib.vertical
    else:
        boldk = 1.0 + (st.weight - 86.0) / 86.0 * 0.16
        W = Wn * st.wf * boldk
        if hk == "X":
            W *= (st.XH / 518.0) ** 0.6
        if st.mono:
            W = max(st.mono_w - 2 * st.sb * 0.55, st.nib.vertical) if Wn > 220 else Wn * 0.9
    g = skeleton.G(st, W, H)
    fn(g)
    return g.out, sp


def place(st, contours, sp):
    xs = [x for c in contours for x, _ in c]
    if not xs:
        return [], int(st.space)
    x0, x1 = min(xs), max(xs)
    ink = x1 - x0
    if st.mono:
        adv = st.mono_w
        shift = (adv - ink) / 2.0 - x0
    else:
        lsb, rsb = side(st, sp[0]), side(st, sp[1])
        adv = ink + lsb + rsb
        shift = lsb - x0
    k = math.tan(math.radians(st.slant))
    mid = st.XH * 0.5
    out = []
    for c in contours:
        out.append([(x + shift + (y - mid) * k, y) for x, y in c])
    return out, int(round(adv))


def ttglyph(contours):
    pen = TTGlyphPen(None)
    for c in contours:
        pts = [(int(round(x)), int(round(y))) for x, y in c]
        pts = [p for i, p in enumerate(pts) if p != pts[i - 1]]
        if len(pts) < 3:
            continue
        pen.moveTo(pts[0])
        for p in pts[1:]:
            pen.lineTo(p)
        pen.closePath()
    return pen.glyph()


def weight_class(st):
    w = st.weight
    for lim, cls in ((35, 100), (55, 300), (100, 400), (125, 500), (160, 700), (190, 800)):
        if w < lim:
            return cls
    return 900


def build(st):
    order = [".notdef", "space"]
    glyf = {}
    hmtx = {}
    cmap = {0x20: "space", 0xA0: "space"}
    # .notdef — пустая рамка
    nd = skeleton.G(st, 400, st.CAP)
    nd.loop([(nd.vh, nd.hh), (nd.vh, st.CAP - nd.hh), (400 - nd.vh, st.CAP - nd.hh), (400 - nd.vh, nd.hh)])
    c, adv = place(st, nd.out, "ss")
    glyf[".notdef"] = ttglyph(c)
    hmtx[".notdef"] = (adv, 0)
    glyf["space"] = TTGlyphPen(None).glyph()
    hmtx["space"] = (int(st.space), 0)
    for ch in skeleton.REG:
        name = "uni%04X" % ord(ch)
        contours, sp = draw_glyph(st, ch)
        c, adv = place(st, contours, sp)
        order.append(name)
        cmap[ord(ch)] = name
        glyf[name] = ttglyph(c)
        xs = [x for cc in c for x, _ in cc]
        hmtx[name] = (adv, int(round(min(xs))) if xs else 0)
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyf)
    fb.setupHorizontalMetrics(hmtx)
    asc, desc = st.ASC + 120, st.DESC - 60
    fb.setupHorizontalHeader(ascent=asc, descent=desc)
    style_name = "Italic" if st.slant else "Regular"
    fam = st.name
    fb.setupNameTable({
        "familyName": fam,
        "styleName": style_name,
        "uniqueFontIdentifier": f"{fam.replace(' ', '')}-{style_name};1.000",
        "fullName": fam if not st.slant else fam,
        "psName": fam.replace(" ", ""),
        "version": "Version 1.000",
        "copyright": "Elements original fonts (generated by tools/fontgen)",
    })
    fb.setupOS2(
        version=4,
        usWeightClass=weight_class(st),
        fsSelection=(0x01 if st.slant else 0x40) | 0x80,
        sTypoAscender=asc, sTypoDescender=desc, sTypoLineGap=0,
        usWinAscent=asc + 40, usWinDescent=-desc + 40,
        sxHeight=st.XH, sCapHeight=st.CAP,
        achVendID="NONE",
        ulCodePageRange1=(1 << 0) | (1 << 2),
    )
    fb.font["OS/2"].recalcUnicodeRanges(fb.font)
    fb.setupPost(keepGlyphNames=False, italicAngle=-st.slant)
    fb.font["head"].macStyle = 2 if st.slant else 0
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, st.file)
    fb.save(path)
    return path, len(order)


