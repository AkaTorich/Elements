def proof(paths):
    from PIL import Image, ImageDraw, ImageFont
    os.makedirs(PROOF, exist_ok=True)
    ui = ImageFont.truetype("C:/Windows/Fonts/segoeui.ttf", 15)
    # один лист на шрифт
    for st, path in paths:
        img = Image.new("RGB", (1500, 520), (14, 16, 24))
        d = ImageDraw.Draw(img)
        d.text((20, 10), st.name, font=ui, fill=(140, 160, 190))
        y = 40
        for size in (40, 22):
            f = ImageFont.truetype(path, size)
            for line in (LINES if size == 40 else LINES[5:]):
                d.text((20, y), line, font=f, fill=(235, 238, 245))
                y += int(size * 1.32)
            y += 6
        img.save(os.path.join(PROOF, st.file.replace(".ttf", ".png")))
    # обзор: все 30 одной картинкой
    img = Image.new("RGB", (1600, 60 + 62 * len(paths)), (14, 16, 24))
    d = ImageDraw.Draw(img)
    y = 20
    for st, path in paths:
        d.text((20, y + 12), st.name, font=ui, fill=(140, 160, 190))
        f = ImageFont.truetype(path, 34)
        d.text((260, y), "Съешь же ещё этих мягких булок  Quick Brown Fox 0123", font=f, fill=(235, 238, 245))
        y += 62
    img.save(os.path.join(PROOF, "_all.png"))


if __name__ == "__main__":
    want = sys.argv[1:]
    made = []
    for i, st in enumerate(STYLES, 1):
        if want and str(i) not in want and st.name not in want:
            continue
        path, n = build(st)
        print("%2d %-24s %4d glyphs %7d bytes  %s" % (i, st.name, n, os.path.getsize(path), st.file))
        made.append((st, path))
    proof(made)
    print("proof:", PROOF)
